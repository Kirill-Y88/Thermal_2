package org.kpush88.Thermal_2.v3;

/**
 * Аппарат — элемент схемы, который не является участком трассы: котёл, турбина,
 * подогреватель, деаэратор, конденсатор, насос.
 *
 * <p>На этом шаге важен только тип элемента: аппарат запрещено соединять с аппаратом
 * напрямую, между ними обязателен участок трассы ({@link Line}). Поэтому в v3 аппараты
 * представлены одним классом-заглушкой, а собственные порты и параметры (КПД, недогрев,
 * давление отбора) появятся у конкретных классов вместе с расчётом состояний.
 *
 * <p>Связи аппарата задаются схемой: {@link Scheme#link} добавляет их в список входов или
 * выходов элемента, поэтому число и порядок связей определяются сборкой трассы.
 */
public class Device extends Element {

    public Device(String uname) {
        super(uname);
    }

    public Device(Long id, String uname) {
        super(id, uname);
    }
}
