package org.kpush88.Thermal_2.v3;

/**
 * Участок трассы — труба ({@link Pipe}) или тройник ({@link PipeTee}).
 *
 * <p>Аппараты соединяются только участками трассы: связь {@link Connection} — это сварной
 * стык двух элементов, а не линия. Поэтому связь «аппарат → аппарат» запрещена и
 * сообщается валидатором ({@link Scheme#validate()}), а любая связь котла с турбиной,
 * отбора с подогревателем или насоса с трактом существует на схеме как элемент этой
 * иерархии. Тройник — тоже участок трассы: разветвление и слияние потоков возможны только
 * внутри элемента, связью их выразить нельзя.
 *
 * <p>Общие для всех участков параметры трассы — понижение давления, теплопотери в
 * окружающую среду, задержка транспорта — появятся здесь; у аппаратов коэффициенты свои.
 */
public abstract class Line extends Element {

    protected Line() {
    }

    protected Line(String uname) {
        super(uname);
    }

    protected Line(Long id, String uname) {
        super(id, uname);
    }
}
