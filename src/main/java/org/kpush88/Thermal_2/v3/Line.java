package org.kpush88.Thermal_2.v3;

import lombok.Getter;

/**
 * Участок трассы — труба ({@link Pipe}) или тройник ({@link PipeTee}).
 *
 * <p>Аппараты соединяются только участками трассы: связь {@link Connection} — это сварной
 * стык двух портов, а не линия. Поэтому связь «аппарат → аппарат» запрещена и сообщается
 * валидатором ({@link Scheme#validate()}), а любая связь котла с турбиной, отбора с
 * подогревателем или насоса с трактом существует на схеме как элемент этой иерархии.
 * Тройник — тоже участок трассы: разветвление и слияние потоков возможны только внутри
 * элемента, связью их выразить нельзя.
 *
 * <p>Участок принадлежит одному контуру ({@link SpaceType}): паропровод — паровой, линия
 * основного конденсата — водяной. Контур задаётся конструктором и определяет контур всех
 * портов участка, поэтому труба не может «сменить контур» по дороге: это сделал бы только
 * аппарат, и то внутри себя.
 *
 * <p>Общие для всех участков параметры трассы — понижение давления, теплопотери в
 * окружающую среду, задержка транспорта — появятся здесь; у аппаратов коэффициенты свои.
 */
public abstract class Line extends Element {

    /** Контур участка: паропровод или водяной тракт. */
    @Getter
    private final SpaceType space;

    protected Line(SpaceType space) {
        this.space = space;
    }

    protected Line(String uname, SpaceType space) {
        super(uname);
        this.space = space;
    }

    protected Line(Long id, String uname, SpaceType space) {
        super(id, uname);
        this.space = space;
    }
}
