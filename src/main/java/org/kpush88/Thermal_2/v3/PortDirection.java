package org.kpush88.Thermal_2.v3;

/**
 * Направление порта: {@link #IN} — среда входит в элемент, {@link #OUT} — выходит из него.
 *
 * <p>Направление — свойство порта, а не места в конкретной сборке: вход турбины всегда вход,
 * даже если для отладки его временно ни с чем не соединили. Поэтому связь можно создать
 * только «{@code OUT} → {@code IN}», и проверка направления не зависит от того, заполнена
 * схема или нет ({@link Scheme#link}).
 */
public enum PortDirection {

    /** Вход элемента: среда приходит в аппарат или участок трассы. */
    IN("вход"),

    /** Выход элемента: среда уходит из аппарата или участка трассы. */
    OUT("выход");

    private final String title;

    PortDirection(String title) {
        this.title = title;
    }

    /** Название направления для сообщений об ошибках. */
    public String title() {
        return title;
    }
}
