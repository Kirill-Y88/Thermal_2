package org.kpush88.Thermal_2.v3.calc;

/**
 * Этап расчёта тепловой схемы — то, что журнал ({@link CalculationJournal}) фиксирует
 * отдельным снапшотом ({@link SchemeState}).
 *
 * <p>Этапы идут строго по порядку объявления, и порядок — не украшение, а правило расчёта:
 * входные данные известны до расчёта, участки трассы переносят их без решения системы,
 * состояния на выходах аппаратов считаются по параметрам конструкции, и только потом
 * решаются балансы. Каждый следующий этап опирается на предыдущий, поэтому журнал запрещает
 * писать в уже зафиксированный этап и требует, чтобы первым был {@link #INPUT}.
 *
 * <p>Этапы {@link #SOLVED} и {@link #RESULT} пока объявлены, но не используются: система
 * балансов появится следующим шагом. Журнал от этого не меняется — он лишь фиксирует, что
 * после {@link #RESOLVED} расходам ещё предстоит появиться, и {@link SchemeState#missing()}
 * честно их перечисляет.
 */
public enum Stage {

    /** Входные данные: ГУ на связях и параметры конструкции на элементах. */
    INPUT("входные данные"),

    /** Перенос по участкам трассы: параметры на связях до и после трубы. */
    NORMALIZED("перенос по участкам трассы"),

    /** Состояния на выходах аппаратов: давления, энтальпии, недогревы, работа насосов. */
    RESOLVED("состояния рассчитаны"),

    /** Балансы массы и энергии решены: появились расходы во всех сечениях. */
    SOLVED("балансы решены"),

    /** Показатели цикла: мощности, теплоты, КПД. */
    RESULT("показатели рассчитаны");

    private static final Stage[] ALL = values();

    private final String title;

    Stage(String title) {
        this.title = title;
    }

    /** Название этапа для отчётов и сообщений об ошибках. */
    public String title() {
        return title;
    }

    /** Следующий этап; {@code null} у последнего. */
    public Stage next() {
        return this == RESULT ? null : ALL[ordinal() + 1];
    }

    /** Этап наступил позже указанного. */
    public boolean isAfter(Stage other) {
        return ordinal() > other.ordinal();
    }
}
