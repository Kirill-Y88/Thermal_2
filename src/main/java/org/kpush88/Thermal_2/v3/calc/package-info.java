/**
 * Расчётный слой v3: этапы расчёта, журнал и снапшоты состояний.
 *
 * <p>Схема ({@link org.kpush88.Thermal_2.v3.Scheme}) описывает конструкцию: элементы, порты и
 * связи. Состояние рабочего тела живёт в связях, но меняется не напрямую, а через
 * {@link org.kpush88.Thermal_2.v3.calc.CalculationJournal}: он записывает величину и её
 * происхождение ({@link org.kpush88.Thermal_2.v3.calc.Origin}) — этап и владельца. Снапшот
 * ({@link org.kpush88.Thermal_2.v3.calc.SchemeState}) — неизменяемая копия всех сечений на
 * этапе, поэтому история расчёта сохраняется целиком.
 *
 * <p>Этапы: {@link org.kpush88.Thermal_2.v3.calc.Stage#INPUT} → {@code NORMALIZED} →
 * {@code RESOLVED} → {@code SOLVED} → {@code RESULT}. Журнал и снапшоты — механизм этапов;
 * расчёт по этапам ведёт {@link org.kpush88.Thermal_2.v3.calc.StateResolver}: он применяет
 * модели элементов ({@link org.kpush88.Thermal_2.v3.calc.ElementModel}) через
 * {@link org.kpush88.Thermal_2.v3.calc.StateAccess}, повторяя проходы до неподвижной точки.
 *
 * <p>Модели делятся на три вида. <b>Переносы</b> (труба, тройник) копируют состояние по
 * участку трассы — это физика участка без потерь. <b>Смешение</b> (смешивающий подогреватель,
 * деаэратор, сливающий тройник) считает энтальпию выхода по балансу энергии входов; для него
 * нужны расходы. <b>Термодинамика аппаратов</b> переводит параметры конструкции в состояние по
 * IF97 ({@link org.kpush88.Thermal_2.v3.thermo.WaterSteam}): котёл — давление и температуру
 * свежего пара в энтальпию, турбина — изоэнтропное расширение отсеков с поправкой на ηoi,
 * поверхностный подогреватель — насыщенный дренаж и недогрев воды, конденсатор — конденсат на
 * линии насыщения, насос — напор и работу. Массовый баланс канала определяет расход, если он
 * единственный неизвестный.
 *
 * <p>Всё, что требует решения системы уравнений (распределение расходов по отборам, теплота
 * аппарата), остаётся незаданным и перечисляется в
 * {@link org.kpush88.Thermal_2.v3.calc.SchemeState#missing()}. По этому отчёту
 * {@link org.kpush88.Thermal_2.v3.calc.FlowSystem} собирает систему балансов массы и энергии:
 * неизвестные — расходы связей, уравнения — балансы каналов и балансы энергии аппаратов, а
 * масштаб задаёт граничный расход. Система решается на этапе {@code SOLVED} и может быть
 * недоопределённой (замкнутый цикл без граничного расхода) — тогда она сообщает ранг и
 * неопределяемые расходы, а не подставляет «удобное» решение.
 *
 * <p>Показатели цикла считает {@link org.kpush88.Thermal_2.v3.calc.CycleSolver}: он доводит
 * расчёт до {@code RESOLVED}, решает балансы под заданной электрической мощностью турбины и
 * подбирает расход свежего пара внешней итерацией по коэффициенту регенерации, замыкая журнал
 * этапом {@code RESULT}. Мощности, теплоты и КПД при этом остаются в
 * {@link org.kpush88.Thermal_2.v3.calc.CycleResult}: это свёртка состояний, а не состояние
 * сечения.
 */
