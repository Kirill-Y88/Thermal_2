package org.kpush88.Thermal_2.v3.calc;

import java.util.Objects;

/**
 * Происхождение величины в сечении: на каком этапе и каким владельцем она записана.
 *
 * <p>Это и есть замена флагу «поле задано/рассчитано». Флаг отвечает на вопрос «есть ли
 * значение», но не на вопрос «откуда оно», поэтому не позволяет отличить ГУ от результата
 * расчёта, а при повторном расчёте его пришлось бы сбрасывать вручную. Пара
 * «этап + владелец» отвечает на оба вопроса и делает конфликт видимым: если давление в
 * сечении уже записано на этапе {@link Stage#INPUT}, а модель пытается записать другое
 * значение на этапе {@link Stage#RESOLVED}, журнал отказывает и называет обоих.
 *
 * <p>Владелец — имя элемента (или «исходные данные схемы» для значений, занесённых до
 * расчёта), а не объект: снапшот должен переживать сериализацию и сравнение отчётов, поэтому
 * в нём нет ссылок на элементы.
 *
 * @param stage этап, на котором величина появилась
 * @param owner кто её записал: имя элемента или «исходные данные схемы»
 */
public record Origin(Stage stage, String owner) {

    public Origin {
        Objects.requireNonNull(stage, "stage");
        if (owner == null || owner.isBlank()) {
            throw new IllegalArgumentException("у происхождения величины должен быть владелец");
        }
    }

    /** Значение занесено до расчёта, то есть является входным данным. */
    public boolean isInput() {
        return stage == Stage.INPUT;
    }

    /** Подпись «этап · владелец» для сообщений: «INPUT (входные данные) · Котёл». */
    public String describe() {
        return stage.name() + " (" + stage.title() + ") · " + owner;
    }
}
