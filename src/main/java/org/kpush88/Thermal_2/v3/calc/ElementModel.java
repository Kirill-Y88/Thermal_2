package org.kpush88.Thermal_2.v3.calc;

import org.kpush88.Thermal_2.v3.Element;

/**
 * Модель элемента на одном этапе расчёта: что из известного в сечениях следует для остальных
 * сечений этого элемента.
 *
 * <p>Модель не хранит состояние и не знает о порядке проходов: она получает элемент и
 * {@link StateAccess}, читает известные величины и записывает те, которые из них следуют.
 * Запись идёт через журнал, поэтому у каждой вычисленной величины остаётся происхождение
 * «этап + имя элемента» — по нему потом видно, чей это результат.
 *
 * <p>Модели живут в расчётном слое ({@code calc}), а не в классах элементов: домен описывает
 * конструкцию (порты, каналы, проверки) и не должен зависеть от этапов и журнала. Кроме того,
 * одну и ту же конструкцию можно считать разными моделями (труба без потерь и труба с
 * потерями), не меняя класс элемента. Тип элемента при этом остаётся точкой ветвления —
 * ровно так, как записано в его назначении ({@link org.kpush88.Thermal_2.v3.ElementType}).
 *
 * <p>Возвращаемое число записанных величин — единственное, что нужно резолверу: проход
 * повторяется, пока хоть одна модель что-то добавляет. Поэтому модели могут быть написаны в
 * любом порядке и не обязаны сами обходить схему.
 */
public interface ElementModel {

    /** Название модели для отчётов: «труба без потерь», «массовый баланс». */
    String title();

    /** Этап, на котором модель работает. */
    Stage stage();

    /** Модель применима к элементу. */
    boolean supports(Element element);

    /**
     * Дополняет состояние элемента тем, что следует из уже известных величин.
     *
     * @return сколько величин записано (0 — модель ничего не добавила)
     * @throws IllegalStateException если известные величины противоречат модели
     */
    int resolve(Element element, StateAccess access);
}
