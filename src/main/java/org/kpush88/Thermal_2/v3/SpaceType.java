package org.kpush88.Thermal_2.v3;

/**
 * Контур аппарата, к которому относится порт: паровая или водяная сторона.
 *
 * <p>Это <b>не</b> фаза рабочего тела. Дренаж подогревателя — вода, но он греет питательную
 * воду и поэтому принадлежит паровой стороне аппарата: контур — свойство места в схеме, а
 * не параметр среды. Именно поэтому тип заменил прежнюю роль среды
 * ({@code HeatTransferType} в v2): роль зависела от аппарата и не давала никаких проверок,
 * а контур задаёт проверяемое правило.
 *
 * <p>Правило: <b>у связи оба конца принадлежат одному контуру</b>
 * ({@link Scheme#link} отвергает несовпадение). Смена контура происходит только внутри
 * элемента — в котле (вода → пар), в конденсаторе (выхлоп → конденсат), в деаэраторе и
 * смешивающем подогревателе (пар и дренажи смешиваются с водой). Поэтому контурная
 * принадлежность связи — величина, которую можно проверить, тогда как совпадение ролей в
 * v2 проверять было нельзя.
 *
 * <p>По контурам строится граф потоков: {@link Scheme#flowGraph(SpaceType)} даёт паровой
 * или водяной тракт, а переходы между контурами остаются внутри элементов и описываются их
 * уравнениями.
 */
public enum SpaceType {

    /** Паровая сторона: свежий пар, отборы, выхлоп, греющий пар и его дренажи. */
    STEAM("паровая сторона"),

    /** Водяная сторона: питательная вода, основной конденсат, напор насосов. */
    WATER("водяная сторона");

    private final String title;

    SpaceType(String title) {
        this.title = title;
    }

    /** Название контура для отчётов и сообщений об ошибках. */
    public String title() {
        return title;
    }
}
