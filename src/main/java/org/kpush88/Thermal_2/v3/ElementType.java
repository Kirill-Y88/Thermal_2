package org.kpush88.Thermal_2.v3;

/**
 * Тип элемента схемы — дискриминатор для загрузчика, отчётов и выбора модели расчёта.
 *
 * <p>Физика элемента живёт в его классе, а не в этом перечислении: типом нельзя выразить
 * «три зоны подогревателя» или «КПД отсека». Тип нужен там, где класс недоступен — при
 * чтении схемы из файла и при ветвлении расчёта по виду оборудования.
 */
public enum ElementType {

    /** Котёл: питательная вода → свежий пар. */
    BOILER,

    /** Турбина: свежий пар → отборы и выхлоп. */
    TURBINE,

    /** Поверхностный подогреватель: пар греет воду через стенку. */
    SURFACE_HEATER,

    /** Смешивающий подогреватель: пар смешивается с водой. */
    MIXING_HEATER,

    /** Деаэратор: пар и дренажи смешиваются с питательной водой. */
    DEAERATOR,

    /** Конденсатор: выхлоп и дренажи конденсируются в основной конденсат. */
    CONDENSER,

    /** Насос: повышает давление воды. */
    PUMP,

    /** Трубопровод: один вход и один выход. */
    PIPE,

    /** Тройник: разветвление или слияние потоков. */
    PIPE_TEE

}
