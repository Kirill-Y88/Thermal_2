package org.kpush88.Thermal_2.v3;

/**
 * Тройник — участок трассы, в котором поток разветвляется или смешивается.
 *
 * <p>Разветвление и слияние выражаются только внутри элемента: две связи с одного конца
 * турбины неотличимы от второго патрубка на том же конце, поэтому место разделения потоков
 * должно быть отдельным элементом схемы. Тройник — участок трассы, а не аппарат: он
 * находится между двумя аппаратами и не меняет состояние рабочего тела, а только
 * перераспределяет расходы ({@code G_in = G_out1 + G_out2} для разветвления).
 *
 * <p>Число связей тройника не ограничивается: у разветвления один вход и два выхода, у
 * слияния — два входа и один выход. Порядок связей сохраняется, поэтому основной поток и
 * ответвление различимы. Балансы расходов появятся здесь на шаге расчёта.
 */
public class PipeTee extends Line {

    public PipeTee(String uname) {
        super(uname);
    }

    public PipeTee(Long id, String uname) {
        super(id, uname);
    }
}
