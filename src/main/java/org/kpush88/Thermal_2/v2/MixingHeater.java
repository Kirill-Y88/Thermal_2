package org.kpush88.Thermal_2.v2;

/**
 * Смешивающий подогреватель (смеситель). Деаэратор — частный случай с тем же
 * устройством портов: {@link Deaerator}.
 *
 * <p>Греющие потоки (пар отбора, дренажи подогревателей) смешиваются с нагреваемой
 * водой внутри элемента, поэтому выход у него один — поток нагреваемой среды, а на
 * греющей стороне выхода нет. Отсюда и разное число входов: их может быть несколько
 * (по одному соединению на каждый входящий поток), и порядок их добавления сохраняется.
 */
public class MixingHeater extends Element {

    public MixingHeater(String uname) {
        super(uname);
    }

    public MixingHeater(Long id, String uname) {
        super(id, uname);
    }
}