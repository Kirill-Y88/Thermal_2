package org.kpush88.Thermal_2.v2;

/**
 * Конденсатор: выхлоп турбины и дренаж ПНД конденсируются, из горячего колодца уходит
 * основной конденсат.
 *
 * <p>Это поверхностный теплообменник ({@link SurfaceHeater}): пар конденсируется на трубках,
 * а тепло снимается циркуляционной водой. Контур охлаждения — внешний сток тепла, в схеме он
 * пока не моделируется, поэтому у элемента показана только пароводяная сторона: входы
 * «выхлоп» (из турбины) и «дренаж ПНД» (каскад дренажа из ПНД), выход «основной конденсат».
 * Выход один, потому что дренаж в горячем колодце смешивается с конденсатом и уходит вместе
 * с ним, а расходы складываются внутри элемента.
 *
 * <p>Тип переноса на порту — роль среды <b>внутри</b> элемента, а не марка рабочего тела:
 * конденсат покидает конденсатор с греющей стороны ({@link HeatTransferType#HEATING_MEDIUM}),
 * а входит в ПНД уже как нагреваемая среда ({@link HeatTransferType#HEATED_MEDIUM}). Роль
 * меняет элемент, через который среда проходит (здесь — конденсатный насос), поэтому схема
 * и не требует совпадения типов на концах ребра.
 *
 * <p>Давление в конденсаторе и отводимая теплота конденсации появятся здесь же на шаге
 * расчёта состояний; на текущем шаге элемент задаёт только структуру связей.
 */
public class Condenser extends SurfaceHeater {

    public Condenser(String uname) {
        super(uname);
    }

    public Condenser(Long id, String uname) {
        super(id, uname);
    }
}
