package org.kpush88.Thermal_2.v2;

/**
 * Трубопровод — участок трассы между двумя аппаратами: у него есть входное и выходное
 * соединения, а состояние рабочего тела между ними меняется внутри элемента.
 *
 * <p>Труба — обязательный элемент любой связи «аппарат → аппарат»: ребро графа лишь
 * сваривает патрубки, поэтому котёл соединяется с турбиной через паропровод, отбор — с
 * подогревателем через паропровод отбора, а насос — с трактом через напорную линию.
 * Правило проверяет {@link Scheme#validate()}.
 *
 * <p>Сейчас связь «вход → выход» чисто структурная: потерь нет, состояние на выходе
 * равно состоянию на входе, поэтому труба без параметров — тождественное преобразование
 * ({@code G_out = G_in}, {@code p_out = p_in}, {@code h_out = h_in}) и собственных
 * неизвестных в систему уравнений не добавляет. Позже здесь появятся коэффициенты
 * понижения давления и температуры (гидравлическое сопротивление и теплопотери трассы) —
 * именно поэтому участок трубопровода является элементом, а не просто ребром графа.
 */
public class Pipe extends Line {

    public Pipe(String uname) {
        super(uname);
    }

    public Pipe(Long id, String uname) {
        super(id, uname);
    }
}
