package org.kpush88.Thermal_2.v2;

/**
 * Участок трассы — труба ({@link Pipe}) или тройник ({@link PipeTee}).
 *
 * <p>В модели аппараты соединяются только участками трассы: ребро {@link SchemeGraph} —
 * это сварной стык двух патрубков, а не линия. Поэтому ребро «аппарат → аппарат»
 * запрещено и сообщается валидатором ({@link Scheme#validate()}), а любая связь котла с
 * турбиной, отбора с подогревателем или насоса с трактом существует на схеме как элемент
 * этой иерархии. Тройник — тоже участок трассы: разветвление и слияние потоков возможны
 * только внутри элемента, ребром их выразить нельзя.
 *
 * <p>Общие для всех участков параметры трассы — понижение давления, теплопотери в
 * окружающую среду, задержка транспорта — появятся здесь; у аппаратов коэффициенты свои
 * ({@link SurfaceHeater}, {@link MixingHeater}, {@link Turbine}).
 */
public abstract class Line extends Element {

    protected Line() {
    }

    protected Line(String uname) {
        super(uname);
    }

    protected Line(Long id, String uname) {
        super(id, uname);
    }
}
