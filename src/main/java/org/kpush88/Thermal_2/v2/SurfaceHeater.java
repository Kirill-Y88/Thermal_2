package org.kpush88.Thermal_2.v2;

/**
 * Поверхностный подогреватель (ПВД, ПНД, сетевой подогреватель). Конденсатор —
 * частный случай того же теплообменника: {@link Condenser}.
 *
 * <p>Греющая (пар отбора) и нагреваемая (вода) среды разделены поверхностью нагрева и
 * не смешиваются, поэтому у элемента по два порта на каждой стороне: вход и выход пара,
 * вход и выход воды. Расходы сторон независимы и связаны только тепловым балансом,
 * который появится на шаге расчёта.
 *
 * <p>Недогрев до температуры насыщения греющего пара задаётся параметром элемента —
 * тоже на следующем шаге.
 */
public class SurfaceHeater extends Element {

    public SurfaceHeater(String uname) {
        super(uname);
    }

    public SurfaceHeater(Long id, String uname) {
        super(id, uname);
    }
}