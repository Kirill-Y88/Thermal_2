package org.kpush88.Thermal_2.v2;

/**
 * Насос (конденсатный, питательный): повышает давление рабочего тела, не меняя ни его
 * стороны, ни агрегатного состояния.
 *
 * <p>Напорный элемент: вход и выход — один и тот же поток, поэтому расход на выходе равен
 * расходу на входе и уравнение баланса массы насос не внесёт, а состояние изменится только
 * по давлению. Портов поэтому ровно два: один вход и один выход, оба на стороне нагреваемой
 * среды ({@link HeatTransferType#HEATED_MEDIUM}) — насос переводит рабочее тело на тот
 * напор, с которым оно пойдёт дальше по тракту воды.
 *
 * <p>Прирост энтальпии в насосе мал (работа сжатия воды {@code w = v·Δp / η}), но он
 * учитывается: давление на выходе задаётся давлением следующего элемента схемы, а КПД
 * появится параметром здесь же. На текущем шаге элемент задаёт только структуру связей.
 */
public class Pump extends Element {

    public Pump(String uname) {
        super(uname);
    }

    public Pump(Long id, String uname) {
        super(id, uname);
    }
}
