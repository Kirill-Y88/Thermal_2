package org.kpush88.Thermal_2.v2;

/**
 * Деаэратор: смешивающий подогреватель, в котором питательная вода нагревается до
 * насыщения и освобождается от кислорода и других коррозионно-активных газов.
 *
 * <p>Наследует {@link MixingHeater}, потому что греющие потоки (пар отбора, дренаж ПВД)
 * смешиваются с нагреваемой водой прямо в баке. Отсюда и порты: на греющей стороне выхода
 * нет, зато входов несколько — по одному соединению на каждый входящий поток (пар, дренаж
 * ПВД, вода за ПНД), и порядок их добавления сохраняется. Выход один — деаэрированная вода
 * на питательный насос.
 *
 * <p>Давление в деаэраторе и недогрев воды до насыщения появятся здесь же на шаге расчёта
 * состояний; на текущем шаге элемент задаёт только структуру связей.
 */
public class Deaerator extends MixingHeater {

    public Deaerator(String uname) {
        super(uname);
    }

    public Deaerator(Long id, String uname) {
        super(id, uname);
    }
}
