package org.kpush88.Thermal_2.v2;

/**
 * Тройник — участок трассы с ответвлением (или слиянием) потоков.
 *
 * <p>Это единственное место в схеме, где поток делится или складывается: у тройника
 * может быть два входа и один выход (слияние) или один вход и два выхода
 * (разветвление), тогда как у остальных соединений схемы степень не больше единицы.
 * Расходы ветвей связаны балансом массы внутри элемента, который появится на шаге
 * составления уравнений.
 *
 * <p>Тройник — такой же {@link Line}, как и {@link Pipe}: он стоит между аппаратами и
 * удовлетворяет правилу «аппарат соединяется с аппаратом только через участок трассы»
 * ({@link Scheme#validate()}). Потери давления и температуры по ветвям задаются так же,
 * как у трубы: параметрами элемента.
 */
public class PipeTee extends Line {

    public PipeTee(String uname) {
        super(uname);
    }

    public PipeTee(Long id, String uname) {
        super(id, uname);
    }
}
