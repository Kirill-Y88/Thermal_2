package org.kpush88.Thermal_2.v2;

/**
 * Турбина.
 *
 * <p>Порты: один вход — свежий пар, несколько выходов — отборы и выхлоп. Выходы
 * перечисляются по ходу расширения (от первого отбора к последнему, выхлоп — в конце),
 * и этот порядок сохраняется элементом: давление каждого отбора задаётся давлением
 * соответствующего соединения, отдельные вершины под отборы не нужны.
 *
 * <p>Внутренний относительный КПД и параметры отборов появятся здесь же на шаге
 * расчёта состояний; на текущем шаге элемент задаёт только структуру связей.
 */
public class Turbine extends Element {

    public Turbine(String uname) {
        super(uname);
    }

    public Turbine(Long id, String uname) {
        super(id, uname);
    }
}