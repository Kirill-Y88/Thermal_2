package org.kpush88.Thermal_2.v1.core;

/**
 * Элемент тепловой схемы (узел графа): котёл, турбина, подогреватель, деаэратор,
 * конденсатор, насос и т.п.
 *
 * <p>Каждый элемент:
 * <ol>
 *   <li>объявляет свои неизвестные — {@link #declareUnknowns(UnknownRegistry)};</li>
 *   <li>вносит <b>локальные</b> вклады в глобальные уравнения —
 *       {@link #contribute(EquationSystem)}.</li>
 * </ol>
 *
 * <p>Элемент ничего не знает о порядке строк/столбцов матрицы: он оперирует только
 * {@link Variable}. Новый тип элемента добавляется реализацией этого интерфейса и не
 * требует изменений в решателе.
 */
public interface Element {

    /** Человекочитаемое имя элемента (для отчётов и диагностики). */
    String name();

    /** Регистрирует неизвестные элемента в общем реестре (нумерация столбцов). */
    void declareUnknowns(UnknownRegistry registry);

    /** Вносит локальные вклады в глобальную систему балансовых уравнений. */
    void contribute(EquationSystem system);
}
