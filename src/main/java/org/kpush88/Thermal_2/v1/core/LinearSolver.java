package org.kpush88.Thermal_2.v1.core;

/**
 * Стратегия решения квадратной СЛАУ {@code A·x = b}.
 *
 * <p>Вынесена в интерфейс, чтобы решатель можно было заменить (например, реализовать
 * на другом разреженном LU/QR) без изменения элементов схемы и сборщика уравнений.
 */
public interface LinearSolver {

    /**
     * @param a квадратная матрица коэффициентов {@code n×n}
     * @param b вектор правой части длины {@code n}
     * @return вектор неизвестных длины {@code n}
     */
    double[] solve(double[][] a, double[] b);
}
